function grassBlock() {
  const depth = [3, 4, 3, 5, 3, 3, 4, 3, 4, 5, 3, 3, 4, 3, 3, 4];
  const grass = ["#6cc046", "#5fae3a", "#4e9a2f", "#79c94f"], dirt = ["#8b5e3c", "#79502f", "#9a6b47", "#6a4528"];
  return speckle(7, 16, [], (r, x, y) => hex((y < depth[x] ? grass : dirt)[(r() * 4) | 0]));
}
const bedrockBlock = () => speckle(11, 16, ["#7a7a7a", "#555555", "#3a3a3a", "#2a2a2a", "#9a9a9a"]);

// Deepslate-like page backdrop, 32×32, with the faint horizontal seams of cut tiles.
function stoneTile() {
  const px = speckle(3, 32, ["#2a2a2f", "#2f2f35", "#26262b", "#33333a", "#1f1f24"],
    (r, x, y, pal) => (y % 8 === 7 && r() < 0.7 ? pal[4] : pal[(r() * 4) | 0]));
  return paint(32, px);
}

