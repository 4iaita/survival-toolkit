/* ---------- Renderer ---------- */
const hex = c => { const n = parseInt(c.slice(1), 16); return [n >> 16 & 255, n >> 8 & 255, n & 255]; };

// Small seeded random generator so textures look the same on every load.
function rng(seed) {
  return () => {
    seed = (seed + 0x6D2B79F5) | 0;
    let t = Math.imul(seed ^ seed >>> 15, 1 | seed);
    t = t + Math.imul(t ^ t >>> 7, 61 | t) ^ t;
    return ((t ^ t >>> 14) >>> 0) / 4294967296;
  };
}

function paint(size, px) {
  const cv = document.createElement("canvas");
  cv.width = cv.height = size;
  const ctx = cv.getContext("2d");
  const img = ctx.createImageData(size, size);
  px.forEach((p, i) => { if (p) img.data.set([p[0], p[1], p[2], 255], i * 4); });
  ctx.putImageData(img, 0, 0);
  return cv.toDataURL();
}

function fromTemplate(spec) {
  const rows = TPL[spec.t];
  const m = MAT[spec.m] || MAT.iron, s = MAT[spec.s] || MAT.wood;
  const pal = { ...FIXED, 1: m[0], 2: m[1], 3: m[2], 4: m[3], a: s[0], b: s[1], c: s[2], d: s[3], ...spec.c };
  const px = [], soft = [];
  for (let y = 0; y < 16; y++) for (let x = 0; x < 16; x++) {
    const ch = (rows[y] || "")[x] || ".";
    soft.push(SOFT.has(ch));
    px.push(ch === "." ? null : hex(pal[ch] || "#ff00ff"));
  }
  const out = px.slice();
  for (let i = 0; i < 256; i++) {
    if (px[i]) continue;
    const x = i % 16, y = (i / 16) | 0;
    const near = [x > 0 && i - 1, x < 15 && i + 1, y > 0 && i - 16, y < 15 && i + 16];
    const n = near.find(j => j !== false && px[j] && !soft[j]);
    if (n !== undefined) out[i] = px[n].map(v => Math.round(v * 0.3));
  }
  return out;
}

function speckle(seed, size, colors, pick = (r, x, y, pal) => pal[(r() * pal.length) | 0]) {
  const r = rng(seed), pal = colors.map(hex);
  return Array.from({ length: size * size }, (_, i) => pick(r, i % size, (i / size) | 0, pal));
}

const iconCache = {};
function icon(name) {
  if (iconCache[name]) return iconCache[name];
  const spec = ICONS[name] || ICONS["ui:book"];
  return (iconCache[name] = paint(16, spec.gen ? spec.gen() : fromTemplate(spec)));
}
