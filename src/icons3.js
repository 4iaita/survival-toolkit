const stoneBlock = () => speckle(13, 16, ["#8a8a8a", "#7d7d7d", "#959595", "#727272"]);
const slimeBlock = () => speckle(5, 16, [], (r, x, y) => {
  const edge = x < 2 || y < 2 || x > 13 || y > 13, core = x > 4 && x < 11 && y > 4 && y < 11;
  return hex(edge ? "#86dc63" : core ? (r() < 0.5 ? "#4f9a35" : "#5aa83e") : (r() < 0.5 ? "#7fd165" : "#73c45a"));
});

// Lighter (f > 0) or darker (f < 0) version of a hex color.
function tint(color, f) {
  return "#" + hex(color).map(v => Math.round(f > 0 ? v + (255 - v) * f : v * (1 + f)).toString(16).padStart(2, "0")).join("");
}

// Bottle icons are made on demand for any liquid color and bottle shape.
function potionIcon(form, color) {
  const name = `p:${form}:${color}`;
  if (!ICONS[name]) {
    ICONS[name] = { t: form === "drink" ? "potion" : form, c: { 1: tint(color, 0.5), 2: color, 3: tint(color, -0.3), 4: tint(color, -0.55) } };
  }
  return name;
}

